  function ensureMap() {
    if (mapPhase || !mapBox) return;
    if (!mapBox.getBoundingClientRect().width) return;   // not laid out yet
    mapPhase = 1;
    if (!KAKAO_JS_KEY) { fallbackMap(); return; }
    loadKakaoSdk(function () {
      try {
        drawKakaoMap();
      } catch (e) {
        fallbackMap();
      }
    }, fallbackMap);
  }

  function loadKakaoSdk(done, fail) {
    if (window.kakao && window.kakao.maps && window.kakao.maps.load) {
      window.kakao.maps.load(done);
      return;
    }
    var tag = document.createElement('script');
    tag.async = true;
    // autoload=false so the SDK waits for kakao.maps.load() instead of
    // initialising itself against a document that is still being rewritten
    tag.src = 'https://dapi.kakao.com/v2/maps/sdk.js?autoload=false&appkey=' +
      encodeURIComponent(KAKAO_JS_KEY);
    tag.onload = function () {
      if (!window.kakao || !window.kakao.maps) { fail(); return; }
      window.kakao.maps.load(done);
    };
    // an unregistered domain or a wrong key is a 401 on the script itself
    tag.onerror = fail;
    document.head.appendChild(tag);
  }

  function drawKakaoMap() {
    var maps = window.kakao.maps;
    var at = new maps.LatLng(VENUE_LAT, VENUE_LNG);
    var map = new maps.Map(mapBox, {
      center: at,
      level: MAP_LEVEL,
      // The invitation is one long scroll, and a map that panned would swallow
      // the vertical swipe trying to get past it. So the map is fixed and the
      // box is a link to the real thing instead.
      draggable: false,
      scrollwheel: false,
      disableDoubleClickZoom: true
    });
    map.setZoomable(false);
    new maps.Marker({ map: map, position: at });

    var pin = el('div', 'cg-map-pin', VENUE);
    new maps.CustomOverlay({
      map: map,
      position: at,
      content: pin,
      // yAnchor counts in multiples of the content's own height, and
      // .cg-map-pin is a fixed 26px, so 2.5 lifts the label (2.5 - 1) * 26 =
      // 39px clear of the point -- just above the marker standing on it.
      yAnchor: 2.5
    });

    var tap = el('a', 'cg-map-tap');
    tap.href = 'https://map.kakao.com/link/map/' +
      encodeURIComponent(VENUE) + ',' + VENUE_LAT + ',' + VENUE_LNG;
    tap.target = '_blank';
    tap.rel = 'noopener';
    tap.setAttribute('aria-label', VENUE + ' 카카오맵에서 보기');
    mapBox.parentNode.appendChild(tap);

    // The runtime re-lays the page out at every viewport change; a Kakao map
    // measured its container once and does not notice on its own.
    var settle = function () { map.relayout(); map.setCenter(at); };
    window.addEventListener('resize', settle);
    window.addEventListener('orientationchange', settle);

    mapPhase = 2;
  }

