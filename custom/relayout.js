  function openTmap() {
    var ua = navigator.userAgent || '';
    var name = encodeURIComponent(VENUE);
    var goal = '&goalx=' + VENUE_LNG + '&goaly=' + VENUE_LAT;

    if (/Android/i.test(ua)) {
      // Android resolves this on its own: T map if it is installed, the Play
      // Store page if it is not. A bare tmap:// cannot express the second half.
      window.location.href =
        'intent://route?goalname=' + name + goal +
        '#Intent;scheme=tmap;package=' + TMAP_PACKAGE +
        ';S.browser_fallback_url=' + encodeURIComponent(TMAP_PLAY) + ';end';
      return;
    }

    if (/iPad|iPhone|iPod/i.test(ua)) {
      // iOS names the destination differently and says nothing when the app is
      // missing, so the App Store is queued behind a short timer that the page
      // going away -- which is what T map opening looks like -- cancels.
      var toStore = window.setTimeout(function () {
        window.location.href = TMAP_APPSTORE;
      }, 1600);
      var keep = function () { window.clearTimeout(toStore); };
      document.addEventListener('visibilitychange', keep, { once: true });
      window.addEventListener('pagehide', keep, { once: true });
      window.location.href =
        'tmap://route?rGoName=' + name +
        '&rGoX=' + VENUE_LNG + '&rGoY=' + VENUE_LAT;
      return;
    }

    // On a desktop there is no app to hand it to, and T map has no web route
    // planner, so this shows what the button is asking them to install.
    window.open(TMAP_SITE, '_blank', 'noopener');
  }

